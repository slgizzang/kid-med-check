String _n(String s) => s.replaceAll(RegExp(r'[\s·.,()\-]'), '').toLowerCase();

/// 성분(여러 개면 쉼표로 구분)에서 알려진 것의 설명. 없으면 null.
/// 항생제는 알레르기 계열 목록(페니실린계·세팔로스포린계 등)으로도 알아본다.
String? ingredientDescription(String ingredients) {
  final text = _n(ingredients);
  if (text.isEmpty) return null;
  for (final (keys, desc) in _ingredientInfo) {
    if (keys.any((k) => _n(k).length >= 2 ? text.contains(_n(k)) : false)) return desc;
  }
  const antibiotic = {'페니실린계', '세팔로스포린계', '마크로라이드계', '퀴놀론계', '설파제'};
  for (final e in kAllergyClasses.entries) {
    if (!antibiotic.contains(e.key)) continue;
    if (e.value.any((m) => _n(m).length >= 3 && text.contains(_n(m)))) {
      return '세균 감염을 치료하는 항생제(${e.key})예요. 증상이 나아져도 처방받은 기간을 채워 먹는 게 중요해요.';
    }
  }
  return null;
}
