String _n(String s) => s.replaceAll(RegExp(r'[\s·.,()]'), '');

/// 계열 설명. 이름에서 쓰임새를 알 수 없으면 null.
String? classDescription(String cls) {
  final c = _n(cls);
  if (c.isEmpty) return null;
  for (final (keys, text) in _classInfo) {
    if (keys.any((k) => c.contains(_n(k)))) return text;
  }
  // 이름에서 쓰임새를 풀어 쓴다 (예: 기타의 비뇨생식기관용약)
  for (final (key, phrase) in _organs) {
    if (c.contains(key)) {
      return c.startsWith('기타')
          ? '$phrase에 쓰는 약 중 다른 분류에 들지 않는 약이에요.'
          : '$phrase에 쓰는 약이에요.';
    }
  }
  return null;
}
